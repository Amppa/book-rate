/**
 * Translates Traditional Chinese characters to Simplified Chinese characters.
 * @param {string} str
 * @returns {string}
 */
export function toSimplified(str) {
  if (!str) return "";

  let res = "";
  for (const ch of str) {
    res += t2sMap.get(ch) ?? ch;
  }
  return res;
}



